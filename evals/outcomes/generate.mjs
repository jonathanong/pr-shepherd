// Outcome suite: does an agent with the plugin (and Shepherd) get a PR to a
// better outcome than an agent with only GitHub tools? See write.mjs for how
// the two arms differ, and evals/RUNNING.md "Outcome suite" for how to run it.
//
//   node evals/outcomes/generate.mjs [--out evals-outcomes]
//
// The output directory is an eval copy of the plugin: the real skills copied
// byte for byte, a plugin.json that adds one MCP server (`cli`) so each case's
// mocks/cli is served in the with-plugin arm only, and the cases in cases/.
// It must sit below the repository root and outside evals/, so the main suite
// never sees it. Run it with `claude plugin eval <out> --eval-dir cases`.

import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";
import { EVALS_DIR, pruneStaleCases } from "../lib.mjs";
import { SCENARIOS } from "./scenarios.mjs";
import { writeOutcomeCase } from "./write.mjs";

const MARKER = ".pr-shepherd-outcome-evals";
const { values } = parseArgs({ options: { out: { type: "string", default: "evals-outcomes" } } });

const repo = realpathSync(join(EVALS_DIR, ".."));
const outDir = resolve(repo, values.out);
mkdirSync(outDir, { recursive: true });
const real = realpathSync(outDir);
const below = relative(repo, real);
const inEvals = !relative(realpathSync(EVALS_DIR), real).startsWith("..");
if (!below || below.startsWith("..") || inEvals)
  throw new Error(`--out must be below ${repo} and outside evals/, got ${real}`);
if (readdirSync(real).length && !existsSync(join(real, MARKER)))
  throw new Error(`--out ${real} is not empty and was not created by this generator`);
writeFileSync(join(real, MARKER), "Generated by evals/outcomes/generate.mjs.\n");

// The eval copy of the plugin. Skills are copied, never edited; the real
// plugin.json is reused except for the added `cli` server that the mocks answer.
const PLUGIN = join(repo, "plugins", "pr-shepherd");
const manifest = JSON.parse(readFileSync(join(PLUGIN, ".claude-plugin", "plugin.json"), "utf8"));
manifest.mcpServers = { cli: { command: "node", args: ["-e", "0"] } };
delete manifest.userConfig;
rmSync(join(real, "skills"), { recursive: true, force: true });
cpSync(join(PLUGIN, "skills"), join(real, "skills"), { recursive: true });
mkdirSync(join(real, ".claude-plugin"), { recursive: true });
writeFileSync(join(real, ".claude-plugin", "plugin.json"), `${JSON.stringify(manifest, null, 2)}\n`);
const casesDir = join(real, "cases");
mkdirSync(casesDir, { recursive: true });

const slugs = new Set();
for (const spec of SCENARIOS) {
  if (slugs.has(spec.slug)) throw new Error(`duplicate slug ${spec.slug}`);
  slugs.add(spec.slug);
  writeOutcomeCase(spec, casesDir);
}
pruneStaleCases([...slugs], casesDir);
console.log(`\n${slugs.size} outcome cases written to ${casesDir}`);
