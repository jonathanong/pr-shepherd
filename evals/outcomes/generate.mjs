// Outcome suite: does an agent with the plugin (and Shepherd) get a PR to a
// better outcome than an agent with only GitHub tools? See write.mjs for how
// the two arms differ, and evals/RUNNING.md "Outcome suite" for how to run it.
//
//   node evals/outcomes/generate.mjs [--out evals-outcomes]
//
// The output directory must sit below the repository root (plugin eval reads
// --eval-dir there) and outside evals/, so the main suite never sees it.

import { existsSync, mkdirSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";
import { EVALS_DIR, pruneStaleCases } from "../lib.mjs";
import { CI_SCENARIOS } from "./scenarios-ci.mjs";
import { REVIEW_SCENARIOS } from "./scenarios-review.mjs";
import { SAFETY_SCENARIOS } from "./scenarios-safety.mjs";
import { writeOutcomeCase } from "./write.mjs";

export const SCENARIOS = [...REVIEW_SCENARIOS, ...CI_SCENARIOS, ...SAFETY_SCENARIOS].sort((a, b) =>
  a.slug.localeCompare(b.slug),
);

const MARKER = ".pr-shepherd-outcome-evals";
const { values } = parseArgs({ options: { out: { type: "string", default: "evals-outcomes" } } });

const repo = realpathSync(join(EVALS_DIR, ".."));
const outDir = resolve(repo, values.out);
mkdirSync(outDir, { recursive: true });
const real = realpathSync(outDir);
const below = relative(repo, real);
const inEvals = !relative(realpathSync(EVALS_DIR), real).startsWith("..");
if (!below || below.startsWith("..") || inEvals)
  throw new Error(`--out must be below ${repo} and outside evals/, got ${real}`);
if (readdirSync(real).length && !existsSync(join(real, MARKER)))
  throw new Error(`--out ${real} is not empty and was not created by this generator`);
writeFileSync(join(real, MARKER), "Generated by evals/outcomes/generate.mjs.\n");

const slugs = new Set();
for (const spec of SCENARIOS) {
  if (slugs.has(spec.slug)) throw new Error(`duplicate slug ${spec.slug}`);
  slugs.add(spec.slug);
  writeOutcomeCase(spec, real);
}
pruneStaleCases([...slugs], real);
console.log(`\n${slugs.size} outcome cases written to ${real}`);
