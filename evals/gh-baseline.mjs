// gh baseline pilot: does an agent with the plugin and Shepherd's output do
// better than an agent with neither, working from the gh output it would read?
//
// The main suite cannot answer that: in fixture cases both arms see Shepherd's
// output, so its Δ measures only the skill. Here every PR state is written
// twice (gh-baseline-pairs.mjs). `plugin eval` runs both arms of both halves;
// the paired score is the Shepherd half's "with" arm minus the gh half's
// "without" arm, from the same outcome grader.
//
//   node evals/gh-baseline.mjs --out evals-gh
//   claude plugin eval . --eval-dir evals-gh --output-dir <dir> ...
//   node evals/gh-baseline.mjs --analyze <dir>/aggregate-result.json
//
// --out must be a new directory below the repo root (plugin eval reads
// --eval-dir there) and outside evals/, so the main suite never sees it.

import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";
import { EVALS_DIR, pruneStaleCases, writeCase } from "./lib.mjs";
import { pairSpecs } from "./gh-baseline-pairs.mjs";
import { bootstrapDeltas, interval, mean, seedOf } from "./stats.mjs";

const MARKER = ".pr-shepherd-gh-baseline";
const { values: flags } = parseArgs({ options: { out: { type: "string" }, analyze: { type: "string" } } });

if (flags.analyze) analyze(flags.analyze);
else if (flags.out) generate(resolve(flags.out));
else throw new Error("pass --out <dir> or --analyze <aggregate-result.json>");

function generate(outDir) {
  const repo = realpathSync(dirname(EVALS_DIR));
  mkdirSync(outDir, { recursive: true });
  const real = realpathSync(outDir);
  const rel = relative(repo, real);
  if (!rel || rel.startsWith("..") || real === realpathSync(EVALS_DIR) || !relative(realpathSync(EVALS_DIR), real).startsWith(".."))
    throw new Error(`--out must be below ${repo} and outside evals/, got ${real}`);
  if (readdirSync(real).length && !existsSync(join(real, MARKER)))
    throw new Error(`--out ${real} is not empty and was not created by this script`);
  writeFileSync(join(real, MARKER), "Generated by evals/gh-baseline.mjs.\n");
  const specs = pairSpecs();
  for (const spec of specs) writeCase(spec, real);
  pruneStaleCases(specs.map((s) => s.slug), real);
  console.log(`\n${specs.length} cases written to ${real}`);
}

function analyze(path) {
  const { cases } = JSON.parse(readFileSync(path, "utf8"));
  // Same rule as analyze.mjs refuseBroken: a failed run or judge call scores 0,
  // which would read as a gh-only loss.
  const broken = cases.flatMap((c) =>
    Object.entries(c.arms ?? {}).flatMap(([arm, runs]) =>
      runs
        .filter((r) => r.error || (r.graders ?? []).some((g) => /grader threw|judge call failed/i.test(g.explanation ?? "")))
        .map((r) => `${c.name} [${arm}]: ${r.error ?? "grader threw"}`),
    ),
  );
  if (broken.length) throw new Error(`runs did not execute cleanly:\n${broken.join("\n")}`);
  const scores = (name, arm) => {
    const c = cases.find((x) => x.name === name || x.name.endsWith(`/${name}`));
    if (!c) throw new Error(`no case ${name} in ${path}`);
    return c.arms[arm].map((r) => r.score);
  };
  const keys = [...new Set(cases.map((c) => c.name.match(/(\d{2}-[\w-]+)-(?:shepherd|gh)$/)?.[1]).filter(Boolean))];
  const fmt = (x) => x.toFixed(2);
  console.log("| Pair | Shepherd+plugin | gh only | Δ | 95% CI | gh+plugin | Shepherd only |");
  console.log("| --- | --- | --- | --- | --- | --- | --- |");
  for (const key of keys) {
    const sw = scores(`${key}-shepherd`, "with");
    const go = scores(`${key}-gh`, "without");
    const draws = bootstrapDeltas(sw, go, seedOf(key));
    const ci = draws ? interval(draws).map(fmt).join(", ") : "n/a";
    const cells = [mean(sw), mean(go), mean(sw) - mean(go)].map(fmt);
    const extra = [mean(scores(`${key}-gh`, "with")), mean(scores(`${key}-shepherd`, "without"))].map(fmt);
    console.log(`| \`${key}\` | ${cells.join(" | ")} | [${ci}] | ${extra.join(" | ")} |`);
  }
}
